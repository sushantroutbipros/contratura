// Splits the single-file prototype into the three pieces the React app mounts:
//   src/prototype/prototype.css  (wrapper reset + main <style> block)
//   src/prototype/markup.html    (everything between </style> and <script>)
//   src/prototype/prototype.js   (the <script> IIFE, wrapped in an exported init function)
//
// Usage: npm run sync [-- path/to/prototype.html]
// Default source: ../Contractura SCM Prototype.html
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = resolve(root, process.argv[2] || '../Contractura SCM Prototype.html');
const out = resolve(root, 'src/prototype');

const html = readFileSync(src, 'utf8').replace(/^﻿/, '');

function between(text, open, close, from) {
  const a = text.indexOf(open, from);
  if (a < 0) throw new Error('Not found: ' + open);
  const b = text.indexOf(close, a + open.length);
  if (b < 0) throw new Error('Not found: ' + close);
  return { body: text.slice(a + open.length, b), end: b + close.length };
}

// Line 1 wrapper reset, then the authored <style> block.
const wrapper = between(html, '<style>', '</style>', 0);
const main = between(html, '<style>', '</style>', wrapper.end);
const script = between(html, '<script>', '</script>', main.end);
const markup = html.slice(main.end, html.indexOf('<script>', main.end)).trim();

// The markup is mounted inside <div id="app">, so selectors that use a direct
// child of <body> (the sign-in gate) need that extra level.
const css = main.body.replace(/(?<![\w-])body((?::not\([^)]*\)|\.[\w-]+)*)>/g, 'body$1 #app>');

const banner = 'Generated by scripts/sync-prototype.mjs from "' + src.split(/[\\/]/).pop() + '". Edit the prototype HTML and re-run npm run sync.';

mkdirSync(out, { recursive: true });
writeFileSync(resolve(out, 'prototype.css'), '/* ' + banner + ' */\n' + wrapper.body.trim() + '\n' + css.trim() + '\n');
writeFileSync(resolve(out, 'markup.html'), '<!-- ' + banner + ' -->\n' + markup + '\n');
writeFileSync(resolve(out, 'prototype.js'), '/* ' + banner + ' */\n/* eslint-disable */\nexport default function initPrototype(){\n' + script.body.trim() + '\n}\n');

console.log('Synced prototype from ' + src);
